package org.quartz.spring.boot.autoconfigure;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.InputStream;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The configuration metadata the IDE completes {@code application.yml} from: generated by the
 * configuration processor and merged with {@code additional-spring-configuration-metadata.json}.
 */
class ConfigurationMetadataTest {

  private static List<JsonNode> properties() throws Exception {
    try (InputStream in =
        ConfigurationMetadataTest.class.getResourceAsStream(
            "/META-INF/spring-configuration-metadata.json")) {
      assertThat(in).as("generated metadata").isNotNull();
      return JsonMapper.builder().build().readTree(in).get("properties").valueStream().toList();
    }
  }

  @Test
  void everyPropertyIsDescribedAsASentence() throws Exception {
    assertThat(properties())
        .filteredOn(p -> p.get("name").asString().startsWith("spring.quartz."))
        .isNotEmpty()
        .allSatisfy(
            p -> {
              String description = p.get("description").asString();
              assertThat(description).as(p.get("name").asString()).endsWith(".");
              assertThat(Character.isUpperCase(description.charAt(0)))
                  .as(p.get("name").asString())
                  .isTrue();
            });
  }

  @Test
  void removedPropertiesAreFlaggedWithWhatToDoInstead() throws Exception {
    Map<String, JsonNode> byName =
        properties().stream()
            .collect(java.util.stream.Collectors.toMap(p -> p.get("name").asString(), p -> p));

    JsonNode database = byName.get("spring.quartz.job-store.mongodb.database");
    assertThat(database.get("deprecation").get("level").asString()).isEqualTo("error");
    assertThat(database.get("deprecation").get("replacement").asString())
        .isEqualTo("spring.mongodb.database");
    assertThat(
            byName
                .get("spring.quartz.plugins.job-history.enabled")
                .get("deprecation")
                .get("reason")
                .asString())
        .contains("LoggingJobHistoryPlugin bean");
    assertThat(byName.get("spring.quartz.thread-pool.thread-priority").get("deprecation"))
        .isNotNull();
    assertThat(byName.get("spring.quartz.thread-pool.thread-count").get("deprecation")).isNull();
  }
}
